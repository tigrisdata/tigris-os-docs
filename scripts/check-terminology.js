// Fails when docs prose says "log in", "login", "log out", "logout", or a
// related form. Tigris copy uses "sign in" / "sign out" for verbs and
// "sign-in" / "sign-out" for nouns and adjectives.
//
// Usage: node scripts/check-terminology.js [file ...]
// With no arguments it checks every .md and .mdx file in docs/, plus the
// label and title strings in sidebars.js and docusaurus.config.js.
// `npm run lint` runs it, so the CI build job runs it too.
//
// What it skips:
// - fenced code blocks (``` and ~~~) and inline code spans
// - URLs and link targets
// - HTML and JSX tags with their attributes, and {expressions}
// - MDX import and export blocks
// - HTML comments and MDX {/* */} comments
// - frontmatter keys other than title, description, and sidebar_label
// - the files and phrases in EXCLUDED_DIRS and ALLOWED_PHRASES below
//
// To keep one line as it is, put this comment on the line before it:
//
//   {/* terminology-ignore-next-line */}     (MDX)
//   <!-- terminology-ignore-next-line -->    (Markdown)
//   // terminology-ignore-next-line          (sidebars.js, docusaurus.config.js)
//
// Do not put the comment above a page's H1 title: Docusaurus then loses the
// page title and description. Put a CLI command such as `tigris login` in
// inline code instead of ignoring the line, in headings too.

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");

// Paths relative to the repo root, with a trailing slash.
const EXCLUDED_DIRS = [
  "docs/partner-integrations/api/", // generated by `npm run build:apidocs`
  "docs/legal/", // contract text; legal approves wording changes
];

const JS_FILES = ["sidebars.js", "docusaurus.config.js"];

// Third-party terms that are correct as written when they appear outside
// code, such as a product's own button label. Add an entry only when the
// term cannot go in inline code. Each entry is a case-insensitive regex.
const ALLOWED_PHRASES = [];

const IGNORE_DIRECTIVE = "terminology-ignore-next-line";

// "log in" and its forms. \b keeps "backlog in", "dialog in", "changelog",
// and "log ingestion" out.
const PATTERN =
  /\b(?:log(?:ged|ging)?(?: |-)(?:in(?:to)?|out)|log-?in|log-?out)\b/gi;

// "log in" is a noun phrase in "the transaction log in order" or "an access
// log in the bucket". Skip a match when the word before "log" says that "log"
// is a noun, or when the word after "in" starts a place or a format.
const NOUN_BEFORE = new Set(
  (
    "a an the this that each every any its their our your one no access " +
    "audit error event events request query server system debug commit " +
    "transaction write-ahead activity application app change build job " +
    "operation operations replication"
  ).split(" "),
);
const PLACE_AFTER = new Set(
  (
    "order the a an this that these those each every its their json csv " +
    "text plain real production parallel batch batches bulk memory"
  ).split(" "),
);

function suggestion(found) {
  const words = found.toLowerCase().replace("-", " ");
  const map = {
    login: '"sign-in" (noun) or "sign in" (verb)',
    logout: '"sign-out" (noun) or "sign out" (verb)',
    "log in": '"sign in"',
    "log into": '"sign in to"',
    "logged in": '"signed in"',
    "logging in": '"signing in"',
    "logged into": '"signed in to"',
    "logging into": '"signing in to"',
    "log out": '"sign out"',
    "logged out": '"signed out"',
    "logging out": '"signing out"',
  };
  let text = map[words];
  if (found.includes("-")) {
    // "log-in page", "logged-in user": the hyphenated form is an adjective.
    text = text.replace(/ (in|out)/, "-$1");
  }
  if (/^[A-Z]/.test(found)) {
    text = text.replace(/"s/g, '"S');
  }
  return text;
}

// Replace every character except newlines with a space, so that line and
// column numbers stay the same after masking.
function blank(text) {
  return text.replace(/[^\n]/g, " ");
}

// Returns the text with everything that is not prose replaced by spaces.
function maskMarkdown(source) {
  const lines = source.split("\n");
  const out = [];
  let i = 0;

  // Frontmatter: keep only the values of title, description, sidebar_label.
  if (lines[0] === "---") {
    const end = lines.indexOf("---", 1);
    if (end > 0) {
      let keep = false;
      for (; i <= end; i++) {
        const line = lines[i];
        const key = /^([A-Za-z_][\w-]*):(.*)$/.exec(line);
        if (key) {
          keep = ["title", "description", "sidebar_label"].includes(key[1]);
          out.push(keep ? blank(key[1] + ":") + key[2] : blank(line));
        } else if (keep && /^\s/.test(line)) {
          out.push(line);
        } else {
          keep = false;
          out.push(blank(line));
        }
      }
    }
  }

  // Fenced code blocks and MDX import/export blocks.
  let fence = null;
  let esm = false;
  for (; i < lines.length; i++) {
    const line = lines[i];
    const open = /^[\s>]*(`{3,}|~{3,})/.exec(line);
    if (fence) {
      out.push(blank(line));
      if (
        open &&
        open[1][0] === fence[0] &&
        open[1].length >= fence.length &&
        line.trim().replace(/^[>\s]*/, "") === open[1]
      ) {
        fence = null;
      }
      continue;
    }
    if (open) {
      fence = open[1];
      out.push(blank(line));
      continue;
    }
    if (!esm && /^(import|export)\b/.test(line)) {
      esm = true;
    }
    if (esm) {
      if (line.trim() === "") {
        esm = false;
      } else {
        out.push(blank(line));
        continue;
      }
    }
    out.push(line);
  }

  let text = out.join("\n");
  const mask = (re) => {
    text = text.replace(re, blank);
  };

  mask(/<!--[\s\S]*?-->/g);
  mask(/\{\/\*[\s\S]*?\*\/\}/g);
  // Inline code: a run of backticks, then the same run. Stops at a blank line.
  mask(/(`+)(?:(?!\1)(?!\n\s*\n)[\s\S])*?\1/g);
  // {expressions}, innermost first, so that nested braces work.
  let before;
  do {
    before = text;
    mask(/\{[^{}]*\}/g);
  } while (text !== before);
  // HTML and JSX tags, including autolinks such as <https://example.com>.
  mask(/<\/?[A-Za-z][^<>]*>/g);
  // Link targets and reference-style link definitions.
  mask(/\]\([^()\s]*(?:\([^()\s]*\)[^()\s]*)*(?:\s+"[^"]*")?\)/g);
  mask(/^\s*\[[^\]\n]+\]:.*$/gm);
  mask(/\bhttps?:\/\/[^\s)\]>"']+/g);
  return text;
}

// Returns the text with everything except label and title strings replaced
// by spaces.
function maskJs(source) {
  return source
    .split("\n")
    .map((line) => {
      if (/^\s*(\/\/|\/?\*)/.test(line)) {
        return blank(line);
      }
      let kept = blank(line);
      const re = /\b(?:label|title)\s*:\s*(["'`])((?:\\.|(?!\1).)*)\1/g;
      let m;
      while ((m = re.exec(line))) {
        const start = m.index + m[0].length - 1 - m[2].length;
        kept = kept.slice(0, start) + m[2] + kept.slice(start + m[2].length);
      }
      return kept;
    })
    .join("\n");
}

// The 1-based line numbers that an ignore directive covers.
function ignoredLines(source) {
  const lines = source.split("\n");
  const ignored = new Set();
  lines.forEach((line, index) => {
    if (!line.includes(IGNORE_DIRECTIVE)) return;
    let next = index + 1;
    while (next < lines.length && lines[next].trim() === "") next++;
    ignored.add(next + 1);
  });
  return ignored;
}

function wordBefore(text, index) {
  const m = /([\w-]+)[\s*_"']*$/.exec(
    text.slice(Math.max(0, index - 40), index),
  );
  return m ? m[1].toLowerCase() : "";
}

function wordAfter(text, index) {
  const m = /^\s+([\w-]+)/.exec(text.slice(index, index + 40));
  return m ? m[1].toLowerCase() : "";
}

function isNounPhrase(text, match) {
  const found = match[0].toLowerCase();
  if (!/ in$/.test(found)) return false;
  const after = wordAfter(text, match.index + match[0].length);
  if (PLACE_AFTER.has(after)) return true;
  return found === "log in" && NOUN_BEFORE.has(wordBefore(text, match.index));
}

function isAllowed(text, match) {
  return ALLOWED_PHRASES.some((phrase) => {
    const re = new RegExp(phrase.source, "gi");
    let m;
    while ((m = re.exec(text))) {
      if (
        m.index <= match.index &&
        match.index + match[0].length <= m.index + m[0].length
      ) {
        return true;
      }
    }
    return false;
  });
}

function check(file) {
  const rel = path.relative(root, file).split(path.sep).join("/");
  const source = fs.readFileSync(file, "utf8");
  const masked = rel.endsWith(".js") ? maskJs(source) : maskMarkdown(source);
  const ignored = ignoredLines(source);
  const lineStarts = [0];
  for (let i = 0; i < masked.length; i++) {
    if (masked[i] === "\n") lineStarts.push(i + 1);
  }
  const problems = [];
  for (const match of masked.matchAll(PATTERN)) {
    if (isNounPhrase(masked, match) || isAllowed(masked, match)) continue;
    let line = lineStarts.length;
    while (lineStarts[line - 1] > match.index) line--;
    if (ignored.has(line)) continue;
    const col = match.index - lineStarts[line - 1] + 1;
    const found = match[0].replace(/\s+/g, " ");
    problems.push(
      `${rel}:${line}:${col}  found "${found}" → use ${suggestion(found)}`,
    );
  }
  return problems;
}

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(root, full).split(path.sep).join("/");
    if (entry.isDirectory()) {
      if (!EXCLUDED_DIRS.includes(rel + "/")) walk(full, files);
    } else if (/\.mdx?$/.test(entry.name)) {
      files.push(full);
    }
  }
  return files;
}

function main() {
  const args = process.argv.slice(2);
  const files = args.length
    ? args.map((file) => path.resolve(file))
    : [
        ...walk(path.join(root, "docs")),
        ...JS_FILES.map((file) => path.join(root, file)),
      ];
  const problems = files.flatMap(check);
  if (problems.length) {
    console.error(problems.join("\n"));
    console.error(
      `\n${problems.length} terminology problem(s). Use "sign in" / "sign out".` +
        ` To keep a line, put a "${IGNORE_DIRECTIVE}" comment before it` +
        " (see scripts/check-terminology.js).",
    );
    process.exit(1);
  }
  console.log(`check-terminology: ${files.length} files OK`);
}

main();
